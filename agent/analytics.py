"""Safe analytics functions over the AI4I 2020 data.

The language model never writes or runs code. It can only call these
predefined functions with validated arguments, and every number in an answer
comes from an exact pandas computation. (LangChain's pandas agent instead
executes code generated by the model, which is unsafe and harder to test.)
"""
from __future__ import annotations

import math
from pathlib import Path
from typing import Optional

import pandas as pd

DATA_PATH = Path(__file__).resolve().parents[1] / "data" / "ai4i2020.csv"

# user-facing sensor name -> (column, unit)
SENSORS = {
    "air_temperature": ("Air temperature", "K"),
    "process_temperature": ("Process temperature", "K"),
    "temperature_difference": ("Temperature difference", "K"),
    "rotational_speed": ("Rotational speed", "rpm"),
    "torque": ("Torque", "Nm"),
    "power": ("Power", "W"),
    "tool_wear": ("Tool wear", "min"),
}
FAILURE_MODES = {
    "TWF": "tool wear failure",
    "HDF": "heat dissipation failure",
    "PWF": "power failure",
    "OSF": "overstrain failure",
    "RNF": "random failure",
}
PRODUCT_TYPES = {"L": "low quality", "M": "medium quality", "H": "high quality"}
STATISTICS = ("mean", "median", "min", "max", "std")
COMPARISONS = (">", ">=", "<", "<=")


class AnalyticsError(ValueError):
    """Invalid arguments from the model, reported back to it as a tool error."""


def load_data(path: Path | str = DATA_PATH) -> pd.DataFrame:
    df = pd.read_csv(path)
    df["Temperature difference"] = df["Process temperature"] - df["Air temperature"]
    df["Power"] = df["Torque"] * df["Rotational speed"] * 2.0 * math.pi / 60.0
    return df


# ---------------------------------------------------------------- helpers
def _sensor(name: str) -> tuple[str, str]:
    if name not in SENSORS:
        raise AnalyticsError(f"unknown sensor '{name}', use one of {sorted(SENSORS)}")
    return SENSORS[name]


def _filter(df: pd.DataFrame, failed: Optional[bool] = None, product_type: Optional[str] = None,
            failure_mode: Optional[str] = None) -> tuple[pd.DataFrame, str]:
    parts = []
    out = df
    if failed is not None:
        out = out[out["Machine failure"] == (1 if failed else 0)]
        parts.append("failed machines" if failed else "machines without failure")
    if product_type is not None:
        if product_type not in PRODUCT_TYPES:
            raise AnalyticsError(f"unknown product type '{product_type}', use L, M or H")
        out = out[out["Type"] == product_type]
        parts.append(f"product type {product_type}")
    if failure_mode is not None:
        if failure_mode not in FAILURE_MODES:
            raise AnalyticsError(f"unknown failure mode '{failure_mode}', use one of {sorted(FAILURE_MODES)}")
        out = out[out[failure_mode] == 1]
        parts.append(f"{failure_mode} ({FAILURE_MODES[failure_mode]})")
    return out, (", ".join(parts) if parts else "all machines")


def _r(x: float, nd: int = 2) -> float:
    return round(float(x), nd)


# ---------------------------------------------------------------- tools
def dataset_overview(df: pd.DataFrame) -> dict:
    """Size, failures, failure rate, product-type mix and failure-mode counts."""
    n = len(df)
    f = int(df["Machine failure"].sum())
    return {
        "records": n,
        "failures": f,
        "failure_rate_percent": _r(100.0 * f / n),
        "product_types": {t: int((df["Type"] == t).sum()) for t in PRODUCT_TYPES},
        "failure_mode_counts": {m: int(df[m].sum()) for m in FAILURE_MODES},
        "note": "a machine can have more than one failure mode; 'failures' counts machines",
    }


def count_machines(df: pd.DataFrame, failed: Optional[bool] = None, product_type: Optional[str] = None,
                   failure_mode: Optional[str] = None) -> dict:
    """Number of records matching the filters."""
    sub, desc = _filter(df, failed, product_type, failure_mode)
    return {"count": int(len(sub)), "filter": desc}


def failure_rate(df: pd.DataFrame, product_type: Optional[str] = None) -> dict:
    """Failure rate overall or for one product type, plus all types for comparison."""
    sub, desc = _filter(df, product_type=product_type)
    by_type = {t: _r(100.0 * df[df["Type"] == t]["Machine failure"].mean()) for t in PRODUCT_TYPES}
    return {
        "filter": desc,
        "machines": int(len(sub)),
        "failures": int(sub["Machine failure"].sum()),
        "failure_rate_percent": _r(100.0 * sub["Machine failure"].mean()),
        "failure_rate_percent_by_type": by_type,
    }


def sensor_statistic(df: pd.DataFrame, sensor: str, statistic: str = "mean", failed: Optional[bool] = None,
                     product_type: Optional[str] = None, failure_mode: Optional[str] = None) -> dict:
    """mean / median / min / max / std of one sensor for the filtered records."""
    col, unit = _sensor(sensor)
    if statistic not in STATISTICS:
        raise AnalyticsError(f"unknown statistic '{statistic}', use one of {list(STATISTICS)}")
    sub, desc = _filter(df, failed, product_type, failure_mode)
    if sub.empty:
        return {"filter": desc, "records": 0, "value": None, "note": "no records match"}
    value = getattr(sub[col], statistic)()
    return {"sensor": col, "unit": unit, "statistic": statistic, "value": _r(value),
            "records": int(len(sub)), "filter": desc}


def count_threshold(df: pd.DataFrame, sensor: str, comparison: str, value: float,
                    failed: Optional[bool] = None, product_type: Optional[str] = None) -> dict:
    """How many records have sensor <comparison> value, and how many of them failed."""
    col, unit = _sensor(sensor)
    if comparison not in COMPARISONS:
        raise AnalyticsError(f"unknown comparison '{comparison}', use one of {list(COMPARISONS)}")
    sub, desc = _filter(df, failed, product_type)
    ops = {">": sub[col] > value, ">=": sub[col] >= value, "<": sub[col] < value, "<=": sub[col] <= value}
    hit = sub[ops[comparison]]
    n = int(len(hit))
    fails = int(hit["Machine failure"].sum())
    return {"condition": f"{col} {comparison} {value} {unit}", "filter": desc, "count": n,
            "of_which_failed": fails, "failure_rate_percent": _r(100.0 * fails / n) if n else None}


def compare_failed_vs_normal(df: pd.DataFrame, sensor: str) -> dict:
    """Mean of a sensor for failed machines versus machines without failure."""
    col, unit = _sensor(sensor)
    return {"sensor": col, "unit": unit,
            "mean_failed": _r(df[df["Machine failure"] == 1][col].mean()),
            "mean_normal": _r(df[df["Machine failure"] == 0][col].mean())}
